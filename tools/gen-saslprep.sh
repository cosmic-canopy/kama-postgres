0041 FE0F
EOF

perl -ne '
    chomp; next unless length;
    my @cp = split / /;
    my $lit = join("", map { my $v = hex($_); $v > 0xFFFF ? sprintf("\\+%06X", $v) : sprintf("\\%04X", $v) } @cp);
    print "ALTER ROLE kp_gen_saslprep PASSWORD U&\x27$lit\x27;\n";
    print "SELECT rolpassword FROM pg_authid WHERE rolname = \x27kp_gen_saslprep\x27;\n";
' "$tmp/passwords" > "$tmp/body.sql"
{
    echo "SET password_encryption = 'scram-sha-256';"
    echo "SET client_min_messages = warning;"
    echo "DROP ROLE IF EXISTS kp_gen_saslprep;"
    echo "CREATE ROLE kp_gen_saslprep;"
    cat "$tmp/body.sql"
    echo "DROP ROLE kp_gen_saslprep;"
} > "$tmp/query.sql"
"$ROOT/tools/pg.sh" psql --version "$VERSION" -q -A -t -f - < "$tmp/query.sql" > "$tmp/verifiers"
expected=$(grep -c . "$tmp/passwords")
got=$(grep -c '^SCRAM-SHA-256\$' "$tmp/verifiers")
[ "$got" = "$expected" ] || { echo "gen-saslprep: $got verifiers for $expected passwords" >&2; cat "$tmp/verifiers" >&2; exit 1; }
server=$("$ROOT/tools/pg.sh" psql --version "$VERSION" -A -t -c 'SHOW server_version')

perl -e '
    my ($passwords, $verifiers, $testout, $commit, $server) = @ARGV;
    sub utf8hex { my $v = shift; my $s = chr($v); utf8::encode($s); return unpack("H*", $s); }
    open my $p, "<", $passwords or die; my @pw = grep { length } map { chomp; $_ } <$p>;
    open my $v, "<", $verifiers or die; my @ver = grep { /^SCRAM-SHA-256\$/ } map { chomp; $_ } <$v>;
    # test_saslprep.out: the single-byte table. Its one other case, an incomplete UTF-8 sequence, cannot be a
    # kama string, which is always UTF-8, so it has no vector here.
    open my $t, "<", $testout or die;
    my (@sin, @sout);
    while (<$t>) {
        next unless /\|\s*\\x([0-9a-f]+)\s*\|\s*\((.*)\)\s*$/;
        my ($in, $res) = ($1, $2);
        $res =~ /^(?:"\\\\x([0-9a-f]*)")?,(\w+)$/ or die "unrecognized result $res";
        push @sin, $in;
        push @sout, $2 eq "SUCCESS" ? "SUCCESS $1" : $2;
    }
    die "no status vectors" unless @sin == 128;
    print "// GENERATED by tools/gen-saslprep.sh. Do not edit: run the script again.\n//\n";
    print "// SASLprep as PostgreSQL does it:\n";
    print "// - saslprepStatus*: src/test/modules/test_saslprep/expected/test_saslprep.out at PostgreSQL master\n";
    print "//   ($commit):\n";
    print "//   an input, in hex, and its outcome (\"SUCCESS <hex of the output>\" or \"PROHIBITED\").\n";
    print "// - saslprepServer*: a password, as UTF-8 in hex, and the SCRAM verifier the server stored for it\n";
    print "//   (\"SCRAM-SHA-256\$<iterations>:<salt>\$<StoredKey>:<ServerKey>\"), from PostgreSQL $server.\n";
    print "import { std::collections::DynamicArray };\n";
    print "export { saslprepStatusInputs, saslprepStatusResults, saslprepServerPasswords, saslprepServerVerifiers };\n\n";
    my @fns = (["saslprepStatusInputs", \@sin], ["saslprepStatusResults", \@sout],
               ["saslprepServerPasswords", [map { join("", map { utf8hex(hex($_)) } split / /) } @pw]],
               ["saslprepServerVerifiers", \@ver]);
    for my $f (@fns) {
        my ($name, $vals) = @$f;
        print "fn DynamicArray<string> $name() {\n    DynamicArray<string> v = DynamicArray.empty();\n";
        for my $x (@$vals) { die "\${ or quote in a vector" if $x =~ /\$\{|"/; print "    v.add(item: \"$x\");\n"; }
        print "    return v;\n}\n\n";
    }
' "$tmp/passwords" "$tmp/verifiers" "$tmp/test_saslprep.out" "$COMMIT" "$server" > "$ROOT/tests/unit/src/saslprep_vectors.kama"

echo "gen-saslprep: tables from $COMMIT; $got verifiers from PostgreSQL $server"
