#!/bin/sh
# gen-win32-errors.sh — the words libpq uses on Windows for a failure the operating system reports, extracted rather
# than retyped, into src/wire/win32.kama:
#
#   winsockText    libpq's WSErrors table (src/interfaces/libpq/win32.c): what winsock_strerror says for a Winsock
#                  code, before it appends " (0x%08X/%d)"
#   errnoOfWin32   PostgreSQL's _dosmaperr (src/port/win32error.c): the errno its Windows port gives a Win32 code,
#                  which is what libpq then prints through strerror
#   crtStrerror    the UCRT's strerror for each of those errnos, asked of the UCRT itself: libpq built with MSVC links
#                  the UCRT, and its texts are not glibc's ("Not enough space", "Interrupted function call")
#
# The PostgreSQL source is the commit the other generators pin, each file by SHA256. The constants' values come from
# mingw-w64's winerror.h and errno.h (v13.0.0), pinned the same way: they are the Windows ABI's, the same in the
# Windows SDK. The UCRT is asked through a probe built with $CC (default clang), which must target the UCRT: run this
# on Windows, under msys2's UCRT64 (PATH=/c/msys64/ucrt64/bin:$PATH). The probe refuses to build for anything else.
#
# The generated file is committed. Run this again and `git diff` must be empty.
set -eu

PG_COMMIT=c45ba888d7af7b38e33832a0e240e34ca98ef866
WIN32_C_SHA=c68436eb644af8a139cc9beb8922737774b12c4e82fa610d0409b1213f4fdeb7
WIN32ERROR_C_SHA=45e71cc5fb23a6f95244f35b7c8882476439e12239bf2c9b362a6a1b71e6290c
MINGW_COMMIT=de62c283f3383bd825c98518cb0a42ba071d4ac2   # v13.0.0
WINERROR_H_SHA=8d9557ea7c589ff0e52005d3ce08c0bbf8d189a6c37a1b31b977a5ac07d3e431
ERRNO_H_SHA=85bb8bccd9322b2db53a7cc9ee3ebc89951f671f8180a56eac02b9b3bf97f1a5

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
CC=${CC:-clang}
case "$(uname -s)" in
    MINGW*|MSYS*) ;;
    *) echo "gen-win32-errors: run this on Windows (msys2 UCRT64 or Git Bash with its clang): it asks the UCRT itself" >&2; exit 2 ;;
esac
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

fetch() {  # fetch <url> <local name> <sha256>
    curl -fsSL -o "$tmp/$2" "$1"
    got=$(sha256sum "$tmp/$2" | cut -d' ' -f1)
    [ "$got" = "$3" ] || { echo "gen-win32-errors: $2 sha256 $got, want $3" >&2; exit 1; }
}
fetch "https://raw.githubusercontent.com/postgres/postgres/$PG_COMMIT/src/interfaces/libpq/win32.c" win32.c "$WIN32_C_SHA"
fetch "https://raw.githubusercontent.com/postgres/postgres/$PG_COMMIT/src/port/win32error.c" win32error.c "$WIN32ERROR_C_SHA"
fetch "https://raw.githubusercontent.com/mingw-w64/mingw-w64/$MINGW_COMMIT/mingw-w64-headers/include/winerror.h" winerror.h "$WINERROR_H_SHA"
fetch "https://raw.githubusercontent.com/mingw-w64/mingw-w64/$MINGW_COMMIT/mingw-w64-headers/crt/errno.h" errno.h "$ERRNO_H_SHA"

# The UCRT's strerror for 0..42, the errnos _dosmaperr can give among them.
cat > "$tmp/probe.c" <<'EOF'
#include <stdio.h>
#include <string.h>
#ifndef _UCRT
#error "this probe must be built for the UCRT (msys2's UCRT64 toolchain)"
#endif
int main(void) {
    for (int i = 0; i <= 42; i++) printf("%d\t%s\n", i, strerror(i));
    return 0;
}
EOF
"$CC" -o "$tmp/probe.exe" "$tmp/probe.c"
"$tmp/probe.exe" | tr -d '\r' > "$tmp/strerror.tsv"

perl -e '
    use strict; use warnings;
    my ($dir, $pg, $mingw) = @ARGV;
    sub slurp { my $p = shift; open my $f, "<", $p or die "$p: $!"; local $/; <$f> }
    my $winerror = slurp("$dir/winerror.h");
    my $errno = slurp("$dir/errno.h");
    # A constant from a header: a number, __MSABI_LONG(n), or (NAME + n), as these headers write them.
    sub value {
        my ($text, $name, $depth) = @_;
        die "$name: too deep" if $depth > 4;
        $text =~ /^#define[ \t]+\Q$name\E[ \t]+(.+?)[ \t]*(?:\/[\/*].*)?$/m or die "no #define $name";
        my $v = $1;
        return $1 if $v =~ /^(\d+)$/;
        return $1 if $v =~ /^__MSABI_LONG\((\d+)\)$/;
        return value($text, $1, $depth + 1) + $2 if $v =~ /^\((\w+)\s*\+\s*(\d+)\)$/;
        die "$name: cannot read \"$v\"";
    }
    sub lit { my $s = shift; die "\${ in \"$s\"" if $s =~ /\$\{/; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return $s }

    my $win32 = slurp("$dir/win32.c");
    $win32 =~ /WSErrors\[\] =\s*\{(.*?)\n\};/s or die "no WSErrors";
    my $table = $1;
    my @ws;
    while ($table =~ /\{\s*(\w+)\s*,\s*"([^"]*)"\s*\}/g) { push @ws, [$1, $2]; }
    @ws >= 50 or die "only " . scalar(@ws) . " WSErrors";

    my $dos = slurp("$dir/win32error.c");
    $dos =~ /doserrors\[\] =\s*\{(.*?)\n\};/s or die "no doserrors";
    my $dtable = $1;
    my @map;
    while ($dtable =~ /\{\s*(\w+)\s*,\s*(\w+)\s*\}/g) { push @map, [$1, $2]; }
    @map >= 40 or die "only " . scalar(@map) . " doserrors";

    my %text;
    open my $t, "<", "$dir/strerror.tsv" or die;
    while (<$t>) { chomp; my ($n, $s) = split /\t/, $_, 2; $text{$n} = $s; }

    print "// GENERATED by tools/gen-win32-errors.sh from PostgreSQL REL_18_STABLE ($pg),\n";
    print "// src/interfaces/libpq/win32.c and src/port/win32error.c; the constants from mingw-w64 v13.0.0\n";
    print "// ($mingw), winerror.h and errno.h; and the texts of the UCRT\x27s strerror, asked of\n";
    print "// it. Do not edit: change the script and run it again.\n";
    print "//\n// How libpq words a failure the operating system reports on Windows. postgres::wire::strerror uses these there.\n";
    print "export { winsockText, errnoOfWin32, crtStrerror };\n\n";
    print "// libpq\x27s WSErrors table: what winsock_strerror says for a Winsock code, or None for one it does not list.\n";
    print "fn Optional<string> winsockText(int32 code) {\n";
    for my $e (@ws) {
        my ($name, $words) = @$e;
        my $v = $name eq "0" ? 0 : value($winerror, $name, 0);
        printf "    if (code == %d) { return Optional::Some(value: \"%s\"); }   // %s\n", $v, lit($words), $name;
    }
    print "    return Optional::None;\n}\n\n";
    print "// _dosmaperr: the errno PostgreSQL\x27s Windows port gives a Win32 code. The first entry for a code wins, as in its\n";
    print "// loop, and a code it does not list is EINVAL.\n";
    print "fn int32 errnoOfWin32(int32 code) {\n    if (code == 0) { return 0; }\n";
    my %errnos = (value($errno, "EINVAL", 0) => 1);
    for my $e (@map) {
        my ($w, $en) = @$e;
        my $wv = value($winerror, $w, 0);
        my $ev = value($errno, $en, 0);
        $errnos{$ev} = 1;
        printf "    if (code == %d) { return %d; }   // %s -> %s\n", $wv, $ev, $w, $en;
    }
    printf "    return %d;   // EINVAL\n}\n\n", value($errno, "EINVAL", 0);
    print "// The UCRT\x27s strerror for each errno errnoOfWin32 gives.\n";
    print "fn string crtStrerror(int32 n) {\n";
    for my $n (sort { $a <=> $b } keys %errnos) {
        defined $text{$n} or die "no UCRT text for errno $n";
        printf "    if (n == %d) { return \"%s\"; }\n", $n, lit($text{$n});
    }
    print "    return \"Unknown error\";\n}\n";
' "$tmp" "$PG_COMMIT" "$MINGW_COMMIT" > "$ROOT/src/wire/win32.kama"
echo "gen-win32-errors: wrote src/wire/win32.kama"
